"""
Tirumala future-safe inference layer for the 77-feature Optuna CatBoost model.

Primary model:
    tirumala_future_safe_optuna.cbm

This module is intentionally tied to the actual saved model at runtime:
- feature names/order come from model.feature_names_
- categorical positions come from model.get_cat_feature_indices()
- date/calendar/panchang/vacation/season features come from lib.features
- future-known TTD event features come from the 2026-2027 event CSV
- historical crowd-context features are constructed only from dates before
  the target date; recursive forecasts are used only after the last actual
  date when forecasting multiple future dates
- same-day operational bulletin fields are never used

Public API expected by the current Streamlit app:
    predict_pilgrims(target_date, events_df=None)
    forecast_until(end_date_iso, events_df=None)
"""
from __future__ import annotations

