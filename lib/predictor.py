MERGED_PATH = PROJECT_ROOT / "data" / "merged.csv"
EVENTS_PATH = PROJECT_ROOT / "data" / "ttd_tirumala_events_2026_2027.csv"

BAND_SIZE = 5000

# These should NOT appear in the future-safe Optuna model.
FORBIDDEN_OPERATIONAL_COLUMNS = {
    "tonsures_raw",
    "hundi_raw",
    "laddu_raw",
    "annaprasadam_raw",
    "medical_raw",
    "waiting_compartments_raw",
    "waiting_time_raw",
}


# ---------------------------------------------------------------------------
# Model loading / schema
# ---------------------------------------------------------------------------

@functools.lru_cache(maxsize=1)
def load_model() -> CatBoostRegressor:
    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Future-safe Optuna model not found: {MODEL_PATH}\n"
            "Copy tirumala_future_safe_optuna.cbm into the project root."
        )
    model = CatBoostRegressor()
    model.load_model(str(MODEL_PATH))
    return model


@functools.lru_cache(maxsize=1)
def model_schema() -> tuple[list[str], list[int]]:
    model = load_model()
    names = list(model.feature_names_)
    cat_idx = sorted(model.get_cat_feature_indices())

    forbidden = [c for c in names if c in FORBIDDEN_OPERATIONAL_COLUMNS]
    if forbidden:
        raise RuntimeError(
            "The selected model contains same-day operational features, "
            f"so it is NOT the expected future-safe model: {forbidden}"
        )

    # These are the known non-history features generated by features.py.
    feature_columns = set(getattr(feat, "FEATURE_COLUMNS", [])) - {"date"}
    event_columns = {
        "ttd_event_count",
        "is_ttd_event",
        "is_major_ttd_event",
        "ttd_event_importance",
        "ttd_event_names",
        "ttd_event_types",
        "major_ttd_events",
        "is_brahmotsavam_event",
        "is_garuda_seva_event",
        "is_pavitrotsavam",
        "is_rathasaptami",
    }
    history_columns = {
        "pilgrims_lag_1d",
        "pilgrims_lag_7d",
        "pilgrims_lag_14d",
        "pilgrims_same_dow_lag_1w",
        "pilgrims_roll7_mean",
        "pilgrims_roll28_mean",
        "pilgrims_prev_year",
        "pilgrims_prev_2year",
        "pilgrims_prev_3year",
        "pilgrims_prev_364d",
        "prior_years_same_dow_mean",
        "prior_years_same_month_dow_mean",
    }

    unexplained = [
        c for c in names
        if c not in feature_columns
        and c not in event_columns
        and c not in history_columns
    ]
    if unexplained:
        raise RuntimeError(
            "Model expects unsupported feature(s): "
            f"{unexplained}"
        )

    return names, cat_idx


# Backward-compatible internal name used by tests / earlier shell checks.
_model_schema = model_schema


