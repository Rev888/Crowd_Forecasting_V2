@functools.lru_cache(maxsize=1)
def load_events() -> pd.DataFrame:
    if not EVENTS_PATH.exists():
        return pd.DataFrame(
            columns=[
                "start_date", "end_date", "event_name", "shrine", "event_type",
                "major_event", "importance", "calendar_label", "source", "scope",
            ]
        )

    events = pd.read_csv(EVENTS_PATH, dtype=str)
    for col in ("start_date", "end_date"):
        events[col] = pd.to_datetime(events[col], errors="coerce").dt.normalize()

    for col in ("event_name", "event_type", "calendar_label"):
        if col not in events.columns:
            events[col] = ""
        events[col] = events[col].fillna("").astype(str)

    if "major_event" not in events.columns:
        events["major_event"] = 0
    events["major_event"] = pd.to_numeric(events["major_event"], errors="coerce").fillna(0).astype(int)

    if "importance" not in events.columns:
        events["importance"] = 0.0
    events["importance"] = pd.to_numeric(events["importance"], errors="coerce").fillna(0.0)

    return events.dropna(subset=["start_date", "end_date"]).copy()


def _event_features_for_date(day: pd.Timestamp) -> dict:
    events = load_events()
    day = pd.Timestamp(day).normalize()

    if events.empty:
        active = events
    else:
        active = events.loc[
            (events["start_date"] <= day)
            & (events["end_date"] >= day)
        ]

    if active.empty:
        return {
            "ttd_event_count": 0,
            "is_ttd_event": 0,
            "is_major_ttd_event": 0,
            "ttd_event_importance": 0.0,
            "ttd_event_names": "",
            "ttd_event_types": "",
            "major_ttd_events": "",
            "is_brahmotsavam_event": 0,
            "is_garuda_seva_event": 0,
            "is_pavitrotsavam": 0,
            "is_rathasaptami": 0,
        }

    names = active["event_name"].astype(str).tolist()
    types = active["event_type"].drop_duplicates().astype(str).tolist()
    major_mask = active["major_event"].eq(1)
    major_names = active.loc[major_mask, "event_name"].astype(str).tolist()

    text = " ".join(
        active["event_type"].astype(str).tolist()
        + active["event_name"].astype(str).tolist()
    ).lower()

    def has_any(*terms: str) -> int:
        return int(any(term.lower() in text for term in terms))

    return {
        "ttd_event_count": int(len(active)),
        "is_ttd_event": 1,
        "is_major_ttd_event": int(major_mask.any()),
        "ttd_event_importance": float(active["importance"].max()),
        "ttd_event_names": " | ".join(names),
        "ttd_event_types": " | ".join(types),
        "major_ttd_events": " | ".join(major_names),
        "is_brahmotsavam_event": has_any("brahmotsavam"),
        "is_garuda_seva_event": has_any("garuda seva", "garuda"),
        "is_pavitrotsavam": has_any("pavitrotsavam", "pavithrotsavam", "pavitrotsav"),
        "is_rathasaptami": has_any("rathasaptami", "rathasapthami", "ratha sapthami"),
    }


