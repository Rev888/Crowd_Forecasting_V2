@functools.lru_cache(maxsize=4096)
def _date_features(day: date) -> dict:
    day = pd.Timestamp(day).normalize()
    frame = pd.DataFrame({"date": [day.strftime("%Y-%m-%d")]})

    frame = feat.add_calendar_features(frame)
    frame = feat.add_holiday_features(frame)
    frame = feat.add_panchang_features(frame)
    frame = feat.add_administrative_festival_features(frame)
    frame = feat.add_vacation_features(frame)
    frame = feat.add_season_features(frame)

    return frame.iloc[0].to_dict()


def _value_on(series: pd.Series, day: pd.Timestamp) -> float:
    value = series.get(pd.Timestamp(day).normalize(), np.nan)
    return np.nan if value is None or pd.isna(value) else float(value)


def _previous_year_value(day: pd.Timestamp, years: int, actuals: pd.Series) -> float:
    return _value_on(actuals, day - pd.DateOffset(years=years))


def _rolling_mean_before(day: pd.Timestamp, periods: int, history: pd.Series) -> float:
    dates = pd.date_range(
        end=day - pd.Timedelta(days=1),
        periods=periods,
        freq="D",
    )
    values = history.reindex(dates).dropna()
    return float(values.mean()) if not values.empty else np.nan


def _prior_same_weekday_average(day: pd.Timestamp, actuals: pd.Series) -> float:
    values = []
    for years_back in (1, 2, 3):
        base = day - pd.DateOffset(years=years_back)
        window = pd.date_range(
            start=base - pd.Timedelta(days=7),
            end=base + pd.Timedelta(days=7),
            freq="D",
        )
        for x in window:
            if x.weekday() != day.weekday():
                continue
            v = _value_on(actuals, x)
            if not pd.isna(v):
                values.append(v)
    return float(np.mean(values)) if values else np.nan


def _prior_same_month_weekday_average(day: pd.Timestamp, actuals: pd.Series) -> float:
    values = []
    for years_back in (1, 2, 3):
        base = day - pd.DateOffset(years=years_back)
        try:
            month_start = pd.Timestamp(year=base.year, month=day.month, day=1)
            month_end = month_start + pd.offsets.MonthEnd(1)
        except ValueError:
            continue
        for x in pd.date_range(month_start, month_end, freq="D"):
            if x.weekday() != day.weekday():
                continue
            v = _value_on(actuals, x)
            if not pd.isna(v):
                values.append(v)
    return float(np.mean(values)) if values else np.nan


def _history_features(day: pd.Timestamp, running: pd.Series, actuals: pd.Series) -> dict:
    day = pd.Timestamp(day).normalize()
    return {
        "pilgrims_lag_1d": _value_on(running, day - pd.Timedelta(days=1)),
        "pilgrims_lag_7d": _value_on(running, day - pd.Timedelta(days=7)),
        "pilgrims_lag_14d": _value_on(running, day - pd.Timedelta(days=14)),
        "pilgrims_same_dow_lag_1w": _value_on(running, day - pd.Timedelta(days=7)),
        "pilgrims_roll7_mean": _rolling_mean_before(day, 7, running),
        "pilgrims_roll28_mean": _rolling_mean_before(day, 28, running),
        "pilgrims_prev_year": _previous_year_value(day, 1, actuals),
        "pilgrims_prev_2year": _previous_year_value(day, 2, actuals),
        "pilgrims_prev_3year": _previous_year_value(day, 3, actuals),
        "pilgrims_prev_364d": _value_on(actuals, day - pd.Timedelta(days=364)),
        "prior_years_same_dow_mean": _prior_same_weekday_average(day, actuals),
        "prior_years_same_month_dow_mean": _prior_same_month_weekday_average(day, actuals),
    }


# ---------------------------------------------------------------------------
# Full 77-feature row + model inference
# ---------------------------------------------------------------------------

def build_feature_row(day: date, running_history: pd.Series, actuals: pd.Series) -> dict:
    day_ts = pd.Timestamp(day).normalize()
    row = _date_features(day_ts.date())
    row.update(_event_features_for_date(day_ts))
    row.update(_history_features(day_ts, running_history, actuals))

    names, _ = model_schema()
    missing = [name for name in names if name not in row]
    if missing:
        raise RuntimeError(
            "Feature construction is missing model columns: "
            f"{missing}"
        )
    return row


def _predict_row(row: dict) -> float:
    model = load_model()
    names, cat_idx = model_schema()
    cat_positions = set(cat_idx)

    X = pd.DataFrame(
        [{name: row.get(name, np.nan) for name in names}],
        columns=names,
    )

    for i, name in enumerate(names):
        if i in cat_positions:
            X[name] = X[name].map(
                lambda v: "" if v is None or pd.isna(v) else str(v)
            )
        else:
            X[name] = pd.to_numeric(X[name], errors="coerce")

    prediction = float(model.predict(Pool(X, cat_features=cat_idx))[0])
    return max(0.0, prediction)


# ---------------------------------------------------------------------------
# Wait-time display estimate (dashboard only; not a model input)
# ---------------------------------------------------------------------------

def _parse_wait(raw) -> tuple[float, float] | None:
    if raw is None or (isinstance(raw, float) and pd.isna(raw)):
        return None
    nums = [
        float(x)
        for x in re.findall(
            r"\d+(?:\.\d+)?",
            str(raw).replace("\u2013", "-"),
        )
    ]
    if not nums:
        return None
    if len(nums) == 1:
        return nums[0], nums[0]
    return min(nums[0], nums[1]), max(nums[0], nums[1])


@functools.lru_cache(maxsize=1)
def _wait_bins() -> pd.DataFrame:
    df = load_merged()
    if "waiting_time_raw" not in df.columns:
        return pd.DataFrame(columns=["band", "wait_lo", "wait_hi"])

    work = df.dropna(subset=["pilgrims", "waiting_time_raw"]).copy()
    parsed = work["waiting_time_raw"].apply(_parse_wait)
    keep = parsed.notna()
    work = work.loc[keep].copy()
    parsed = parsed.loc[keep]
    if work.empty:
        return pd.DataFrame(columns=["band", "wait_lo", "wait_hi"])

    work["wait_lo"] = parsed.map(lambda p: p[0])
    work["wait_hi"] = parsed.map(lambda p: p[1])
    work["band"] = (work["pilgrims"] // BAND_SIZE) * BAND_SIZE

    return (
        work.groupby("band")[["wait_lo", "wait_hi"]]
        .median()
        .reset_index()
        .sort_values("band")
    )


def _estimate_wait(point: float) -> tuple[float, float] | None:
    bins = _wait_bins()
    if bins.empty:
        return None
    band = (point // BAND_SIZE) * BAND_SIZE
    idx = (bins["band"] - band).abs().idxmin()
    r = bins.loc[idx]
    return float(r["wait_lo"]), float(r["wait_hi"])


def _band(point: float) -> tuple[int, int]:
    lo = int(point // BAND_SIZE) * BAND_SIZE
    return lo, lo + BAND_SIZE


# ---------------------------------------------------------------------------
# Recursive future forecasting
# ---------------------------------------------------------------------------

@functools.lru_cache(maxsize=64)
def _forecast_through(end_d: date) -> tuple[tuple[pd.Timestamp, dict], ...]:
    actuals = actual_series()
    if actuals.empty:
        raise RuntimeError("No actual pilgrim history found in merged.csv.")

    last_actual = pd.Timestamp(actuals.index.max()).normalize()
    end_ts = pd.Timestamp(end_d).normalize()

    if end_ts <= last_actual:
        return tuple()

    # Actual historical values are immutable. Predictions are appended to a
    # separate running series only for dates beyond the actual-data horizon.
    running = actuals.copy().astype(float)
    results: dict[pd.Timestamp, dict] = {}

    cursor = last_actual + pd.Timedelta(days=1)
    while cursor <= end_ts:
        d = cursor.date()
        row = build_feature_row(d, running, actuals)
        point = _predict_row(row)
        running.loc[cursor] = point

        lo, hi = _band(point)
        results[cursor] = {
            "point_estimate": point,
            "range_low": lo,
            "range_high": hi,
            "wait_range_hours": _estimate_wait(point),
            "feature_row": row,
        }
        cursor += pd.Timedelta(days=1)

    return tuple(results.items())


# ---------------------------------------------------------------------------
# Public API for app.py
# ---------------------------------------------------------------------------

def predict_pilgrims(target_date: date, events_df=None) -> dict:
    """Return actual historical value when available, otherwise forecast."""
    d = pd.Timestamp(target_date).normalize()
    actuals = actual_series()

    if d in actuals.index:
        point = float(actuals.loc[d])
        lo, hi = _band(point)
        return {
            "point_estimate": point,
            "range_low": lo,
            "range_high": hi,
            "wait_range_hours": _estimate_wait(point),
            "feature_row": {},
            "is_actual": True,
        }

    table = dict(_forecast_through(d.date()))
    if d not in table:
        raise ValueError(f"Unable to generate forecast for {d.date()}.")

    result = dict(table[d])
    result["is_actual"] = False
    return result


def forecast_until(end_date_iso: str, events_df=None) -> pd.DataFrame:
    end_d = date.fromisoformat(str(end_date_iso)[:10])
    table = dict(_forecast_through(end_d))

    records = [
        {
            "date": ts.date().isoformat(),
            "prediction": float(result["point_estimate"]),
            "lo": int(result["range_low"]),
            "hi": int(result["range_high"]),
            "wait": result.get("wait_range_hours"),
        }
        for ts, result in table.items()
    ]

    return pd.DataFrame(
        records,
        columns=["date", "prediction", "lo", "hi", "wait"],
    ).sort_values("date").reset_index(drop=True)


