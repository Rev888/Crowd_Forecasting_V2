@functools.lru_cache(maxsize=1)
def load_merged() -> pd.DataFrame:
    if not MERGED_PATH.exists():
        raise FileNotFoundError(f"Historical data not found: {MERGED_PATH}")

    df = pd.read_csv(MERGED_PATH, dtype=str)
    required = {"date", "pilgrims_raw"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"merged.csv missing required columns: {sorted(missing)}")

    df["date"] = pd.to_datetime(df["date"], errors="coerce").dt.normalize()
    df["pilgrims"] = pd.to_numeric(
        df["pilgrims_raw"].astype(str).str.replace(",", "", regex=False),
        errors="coerce",
    )

    return (
        df.dropna(subset=["date"])
        .drop_duplicates("date", keep="last")
        .sort_values("date")
        .reset_index(drop=True)
    )


@functools.lru_cache(maxsize=1)
def actual_series() -> pd.Series:
    df = load_merged()
    return (
        df.dropna(subset=["pilgrims"])
        .set_index("date")["pilgrims"]
        .astype(float)
        .sort_index()
    )


_known_actuals = actual_series


def _last_actual_date() -> date | None:
    actuals = actual_series()
    return actuals.index.max().date() if not actuals.empty else None


